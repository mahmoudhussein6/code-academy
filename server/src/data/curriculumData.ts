const getCourseModuleLessons = (courseSlug: string, moduleSlug: string): ILesson[] =>
  lessonsData
    .filter((lesson) => lesson.courseSlug === courseSlug && lesson.moduleSlug === moduleSlug)
    .sort((a, b) => a.order - b.order)
    .map((lesson) => ({
      slug: lesson.slug,
      courseSlug: lesson.courseSlug,
      moduleSlug: lesson.moduleSlug,
      order: lesson.order,
      title: lesson.title,
      summary: lesson.summary,
      readTimeMinutes: lesson.readTimeMinutes,
      contentMarkdown: '',
    }));

