const LanguageContext = createContext<LanguageContextValue | null>(null);

const getInitialLanguage = (): Language => {
  if (typeof window === 'undefined') return 'en';
  return window.localStorage.getItem('code-academy-language') === 'ar' ? 'ar' : 'en';
};

export const LanguageProvider: React.FC<React.PropsWithChildren> = ({ children }) => {
  const [language, setLanguage] = useState<Language>(getInitialLanguage);
  const direction = language === 'ar' ? 'rtl' : 'ltr';

  useEffect(() => {
    window.localStorage.setItem('code-academy-language', language);
    document.documentElement.lang = language;
    document.documentElement.dir = direction;
    document.title =
      language === 'ar'
        ? 'Code Academy | منصة عربية لتعليم تطوير الويب من الصفر'
        : 'Code Academy | Learn Web Development';
  }, [language, direction]);

  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      direction,
      setLanguage,
      t: (arabicText) => (language === 'en' ? translations[arabicText] ?? arabicText : arabicText),
    }),
    [language, direction],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useLanguage = (): LanguageContextValue => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
